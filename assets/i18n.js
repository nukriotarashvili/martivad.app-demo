/**
 * Keys come out of the markup exactly as authored, so one wrapped across source
 * lines carries newlines and indentation. Normalising whitespace on BOTH sides
 * lets the dictionary stay readable on a single line.
 */
const norm = (s) => String(s).replace(/\s+/g, ' ').trim();

const build = (d) => {
  const out = Object.create(null);
  for (const k of Object.keys(d)) out[norm(k)] = d[k];
  return out;
};

const DICT = { ka: null, en: build(en), ru: build(ru) };

/* --------------------------------------------------------------- runtime -- */
const missing = new Set();

export function getLang() {
  try {
    const v = localStorage.getItem(KEY);
    return LANGS.includes(v) ? v : 'ka';
  } catch (e) { return 'ka'; }
}

/**
 * თარგმანი. ka-ზე (ან უცნობ ენაზე) წყარო თავად პასუხია.
 * აკლია? — ქართული რჩება და console.warn ერთხელ ლოგავს.
 */
export function t(src, lang = getLang()) {
  const d = DICT[lang];
  if (!d) return src;
  const v = d[norm(src)];
  if (v === undefined) {
    const id = `${lang}:${src}`;
    if (!missing.has(id)) { missing.add(id); console.warn(`[i18n] missing ${lang}: ${src}`); }
    return src;
  }
  return v;
}

/**
 * თარგმნის მხოლოდ `data-i18n`-იან კვანძებს.
 *
 * ორიგინალი წყარო ატრიბუტშია, ამიტომ გადართვა იდემპოტენტურია — ინგლისურიდან
 * რუსულზე გადასვლა ისევ ქართული წყაროდან ითარგმნება, არა ინგლისურიდან.
 */
export function applyI18n(root = document, lang = getLang()) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const src = el.getAttribute('data-i18n');
    if (src) el.textContent = t(src, lang);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    const src = el.getAttribute('data-i18n-ph');
    if (src) el.setAttribute('placeholder', t(src, lang));
  });
  document.documentElement.lang = lang;
}

export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  try { localStorage.setItem(KEY, lang); } catch (e) { /* საცავი გამორთულია */ }
  applyI18n(document, lang);
  document.dispatchEvent(new CustomEvent('martivad:langchange', { detail: { lang } }));
}

/** გადამრთველი: KA | EN | RU */
export function initLangSwitch(container) {
  if (!container) return;
  const paint = () => {
    const cur = getLang();
    container.innerHTML = LANGS.map((l) =>
      `<button type="button" data-lang="${l}" aria-pressed="${l === cur}">${l.toUpperCase()}</button>`
    ).join('');
  };
  paint();
  container.addEventListener('click', (ev) => {
    const b = ev.target.closest('[data-lang]');
    if (!b) return;
    setLang(b.dataset.lang);
  });
  // Repaint on the event, not after the click: setLang() is also called
  // programmatically, and painting only in the handler left the pressed state
  // pointing at the previous language.
  document.addEventListener('martivad:langchange', paint);
}

/**
 * ტესტისთვის: console-ში `martivadI18n.coverage()` — რომელი გასაღები აკლია.
 * მწვანე შედეგი = ორივე მასივი ცარიელია.
 */
/**
 * Georgian text inside #view that carries NO data-i18n.
 *
 * The key-coverage check below only sees keys that were tagged, so a string
 * nobody tagged is invisible to it — that is exactly how the operation-type
 * dropdown stayed Georgian while the report showed green. This finds that class
 * of gap. User data and chart-of-accounts names legitimately appear here, so
 * the result is a review list, not a failure.
 */
export function untagged(root = document.getElementById('view')) {
  if (!root) return [];
  const ge = /[\u10D0-\u10FF]/;
  const out = new Set();
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = walk.nextNode())) {
    const txt = n.nodeValue.trim();
    if (!txt || !ge.test(txt)) continue;
    const el = n.parentElement;
    if (el && el.closest('[data-i18n]')) continue;
    if (el && el.closest('[data-no-i18n]')) continue;
    out.add(txt.slice(0, 60));
  }
  return [...out];
}

export function coverage() {
  const keys = [...document.querySelectorAll('[data-i18n]')].map((e) => e.getAttribute('data-i18n'));
  const phs = [...document.querySelectorAll('[data-i18n-ph]')].map((e) => e.getAttribute('data-i18n-ph'));
  const all = [...new Set([...keys, ...phs])];
  const report = { total: all.length, missing: { en: [], ru: [] } };
  for (const k of all) {
    if (DICT.en[norm(k)] === undefined) report.missing.en.push(k);
    if (DICT.ru[norm(k)] === undefined) report.missing.ru.push(k);
  }
  return report;
}

